package Switchcase;

public class Vovel {
    public static void main(String[]args){
        int vovel=6;
        switch(vovel){
            case 1:
                System.out.println("a");
                break;
            case 2:
                System.out.println("e");
                break;
            case 3:
                System.out.println("i");
                break;
            case 4:
                System.out.println("o");
                break;
            case 5:
                System.out.println("u");
                break;
            default:
                System.out.println("Consonent");
        }
    }
}
