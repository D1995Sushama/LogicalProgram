package Constructor;

public class Userdefined {
    int c;
    int d;
    Userdefined(){
        c=60;
        d=20;
    }
    public void div(){
        System.out.println("Dividation Of Two Number="+ c/d);
    }
    public void sub(){
        System.out.println("Substraction Of Number="+ (c-d));
    }
}
